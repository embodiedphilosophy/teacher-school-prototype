// Lists every .jpg under public/images so components know which photo slots are filled.
import fs from "node:fs"; import path from "node:path";
const root = path.join(process.cwd(), "public", "images");
const out = [];
(function walk(d) { if (!fs.existsSync(d)) return; for (const e of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, e.name); if (e.isDirectory()) walk(p); else if (e.name.endsWith(".jpg")) out.push(path.relative(root, p).replace(/\.jpg$/, "")); } })(root);
fs.writeFileSync(path.join(process.cwd(), "content", "photo-manifest.ts"), `// GENERATED by scripts/photo-manifest.mjs — do not edit.\nexport const PHOTOS: string[] = ${JSON.stringify(out.sort(), null, 2)};\n`);
console.log(`photo manifest: ${out.length} photos`);
